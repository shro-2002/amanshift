"""Generate eval/out/report.md from the JSON artifacts (doc 09 section 10). No hand-typed numbers."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

OUT = Path(__file__).resolve().parents[2] / "eval" / "out"


def j(name: str) -> dict[str, Any]:
    p = OUT / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def pct(x: float | None) -> str:
    return "n/a" if x is None or x != x else f"{100 * x:.1f} %"


def skill_table(split: dict[str, Any]) -> list[str]:
    lines = ["| Profile | Reference | Hours | Ref events (L>=3) | POD | FAR | CSI | Under-warning | Missed days |",
             "|---|---|---|---|---|---|---|---|---|"]
    for key, p in split.get("profiles", {}).items():
        k = p["k3"]
        days = p["days_k3"]
        lines.append(f"| {key} | {p['reference']} | {k['hours']} | {k['events_ref']} | {pct(k['pod'])} | "
                     f"{pct(k['far'])} | {pct(k['csi'])} | {pct(k['under_warning_rate'])} | "
                     f"{days['missed_days']}/{days['days_with_event']} |")
    return lines


def baseline_table(split: dict[str, Any]) -> list[str]:
    prim = next(iter(split.get("profiles", {}).values()), {})
    k = prim.get("k3", {})
    hours, events = k.get("hours") or 0, k.get("events_ref") or 0
    lines = [f"Event prevalence (reference level >= 3): {events}/{hours} work hours = "
             f"{pct(events / hours if hours else None)}.", "",
             "| Method | POD | FAR | CSI | Under-warning | Exact level agreement |", "|---|---|---|---|---|---|"]
    lines.append(f"| AmanShift (forecast + delta) | {pct(k.get('pod'))} | {pct(k.get('far'))} | "
                 f"{pct(k.get('csi'))} | {pct(k.get('under_warning_rate'))} | "
                 f"{pct(k.get('exact_level_agreement'))} |")
    for name, b in prim.get("baselines_k3", {}).items():
        lines.append(f"| {name} | {pct(b['pod'])} | {pct(b['far'])} | {pct(b['csi'])} | "
                     f"{pct(b['under_warning_rate'])} | {pct(b.get('exact_level_agreement'))} |")
    k4 = prim.get("k4")
    if k4:
        lines += ["", f"STOP events (reference level 4): {k4['events_ref']}/{k4['hours']} work hours; "
                  f"POD {pct(k4['pod'])}, FAR {pct(k4['far'])}, CSI {pct(k4['csi'])}."]
    ci = prim.get("bootstrap95_k3")
    if ci:
        lines.append("")
        lines.append("Bootstrap 95 % CI (1,000 day resamples, seed 20261119): " + "; ".join(
            f"{m} [{pct(v[0])}, {pct(v[1])}]" for m, v in ci.items()))
    return lines


def main() -> int:
    ref, fe, prop = j("reference_checks"), j("forecast_eval"), j("property_tests")
    mut, bench, cost, man = j("checker_mutation"), j("planner_bench"), j("cost_of_safety"), j("manifest")
    sel = json.loads((OUT.parents[1] / "data" / "scenarios" / "s-auh-1.json").read_text())
    L: list[str] = ["# AmanShift evaluation report", "",
                    "Auto-generated by `make eval` (backend/eval/report.py) from `eval/out/*.json`. "
                    "Data-type labels: REAL-OBS, HIST-FCST, SIM-SITE, SYNTH-TEST, NOT-VALIDATED.", ""]
    L += ["## 1 Data and provenance", ""]
    for _name, d in sorted(man.get("datasets", {}).items()):
        L.append(f"- `{d['file']}` — {d['rows']} rows, retrieved {d['retrieved_at']}, sha256 `{d['sha256'][:12]}…`")
    L += ["", "Excluded years: " + "; ".join(f"{y}: {r}" for y, r in fe.get("excluded_years", {}).items()), ""]
    L += ["## 2 Reference reproduction", "",
          f"- Liljegren vs thermofeel test vectors: max abs error "
          f"{ref.get('t_ref_01_liljegren', {}).get('max_abs_error_c', 'n/a')} °C "
          f"({ref.get('t_ref_01_liljegren', {}).get('vectors', 0)} vectors)",
          f"- NIOSH REL/RAL golden table: {len(ref.get('t_ref_02_niosh', {}).get('rows', []))} rows within 0.05 °C",
          f"- Solar geometry 21 Jun: cos zenith {ref.get('t_ref_04_solar', {}).get('max_cos_zenith_21jun')} "
          f"vs {ref.get('t_ref_04_solar', {}).get('expected')}", f"- All pass: **{ref.get('all_pass')}**", ""]
    L += ["## 3 Forecast warning skill (HIST-FCST vs REAL-OBS)", "",
          f"Forecast margin delta = **{fe.get('delta_frozen', {}).get('value')} °C**, rule: "
          f"{fe.get('delta_frozen', {}).get('rule')}; train years {fe.get('delta_frozen', {}).get('train_years')}.",
          f"Lead time: {fe.get('lead_time')}.", ""]
    for label, key in (("Clean holdout 2026", "holdout_clean_2026"), ("Exposed holdout 2025", "holdout_exposed_2025"),
                       ("Train 2024", "train")):
        split = fe.get(key, {})
        err = split.get("wbgt_shade_error", {})
        L += [f"### {label}", "", f"Shade WBGT estimate vs REF-SHADE: MAE {err.get('mae_c')} °C, "
              f"bias {err.get('bias_c')} °C, n = {err.get('n')}.", ""]
        L += skill_table(split) + [""]
        L += ["Primary profile vs baselines (event = level >= 3):", ""] + baseline_table(split) + [""]
    L += ["Limitations: " + "; ".join(fe.get("limitations", [])) + ".", ""]
    L += ["## 4 Fail-safe property tests (SYNTH-TEST)", "", "| Test | Examples | Violations |", "|---|---|---|"]
    for t in prop.get("tests", []):
        L.append(f"| {t['test']} | {t['examples']} | {t['violations']} |")
    L += ["", f"Total examples {prop.get('total_examples')}, failures {prop.get('failures')}.", ""]
    L += ["## 5 Checker mutation results (SYNTH-TEST)", "", "| Operator | Rule | Non-equivalent | Killed | Kill rate |",
          "|---|---|---|---|---|"]
    for name, o in mut.get("operators", {}).items():
        L.append(f"| {name} | {o.get('safety_rule') or '—'} | {o['non_equivalent']} | {o['killed']} | {pct(o['kill_rate'])} |")
    L += ["", f"Overall kill rate {pct(mut.get('kill_rate_total'))}; safety-critical survivors "
          f"{mut.get('safety_critical_survivors')}. {mut.get('note', '')}", ""]
    L += ["## 6 Planner benchmarks (SYNTH-TEST)", "",
          "| Crews / resources | Planner | Priority-weighted unprotected (mean) | Crews stopped (mean) | Sites with checker violations |",
          "|---|---|---|---|---|"]
    for t in bench.get("tiers", []):
        for k in ("amanshift_greedy", "naive_greedy", "no_replan"):
            e = t[k]
            L.append(f"| {t['crews']} / {t['resources']} | {k} | {e['mean_priority_weighted_unprotected']} | "
                     f"{e['mean_crews_stopped']} | {e['sites_with_checker_violations']}/{t['sites']} |")
        L.append(f"| {t['crews']} / {t['resources']} | runtime p50/p95 (ms) | "
                 f"{t['amanshift_greedy']['runtime_ms_p50']} / {t['amanshift_greedy']['runtime_ms_p95']} | | |")
    share = cost.get("permitted_share_of_nominal_pct", {})
    L += ["", "## 7 Cost of safety (SIM-SITE + HIST-FCST, 2026 season)", "",
          f"Nominal: {cost.get('nominal_person_hours')} person-hours (all workers, every hourly tick, "
          f"{cost.get('days')} days); midday break alone removes {cost.get('midday_break_person_hours')} "
          f"({cost.get('midday_break_share_of_nominal_pct')} % of nominal).", "",
          "| Information state | Permitted work person-hours | Share of nominal | Reduction vs full information |",
          "|---|---|---|---|"]
    for m, v in cost.get("permitted_work_person_hours", {}).items():
        L.append(f"| {m} | {v} | {share.get(m)} % | {cost['reduction_vs_full_pct'][m]} % |")
    L += ["", f"{cost.get('note', '')}", ""]
    s = sel.get("selection", {})
    L += [f"Demo scenario: {s.get('date')} at 10:30 GST, levels {s.get('levels')}, rule '{s.get('rule')}'.", ""]
    L += ["## 8 Not validated (NOT-VALIDATED)", "",
          "- Reduction of heat illness or injury (requires field pilot, doc 06 §14).",
          "- Accuracy against onsite measured WBGT/TWL at a worksite.",
          "- Worker comprehension of translated cards (pending native review).",
          "- Supervisor adherence and real-world operational use.", ""]
    L += ["## 9 Reproduce", "", "```bash", "make setup", "make eval   # writes eval/out/*.json and this report",
          "```", ""]
    (OUT / "report.md").write_text("\n".join(L))
    print("report.md written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
